interface I18nValue {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  tCity: (city: string) => string;
  tFeature: (feature: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ckb");

  useEffect(() => {
    // ?lang= wins over the saved choice: it's how a search result, a shared
    // link, or a crawler asks for one specific language, and honouring the
    // visitor's last pick instead would serve them the wrong page. Also what
    // makes each language a distinct URL for hreflang to point at.
    const asked = new URLSearchParams(window.location.search).get("lang");
    const fromUrl = asked && asked in LANGS ? (asked as Lang) : null;
    if (fromUrl) {
      setLangState(fromUrl);
      localStorage.setItem("lang", fromUrl);
      return;
    }
    const saved = (localStorage.getItem("lang") as Lang) || "ckb";
    setLangState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = LANGS[lang].dir;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("lang", l);
    // Move the address bar onto this language's path, so what the visitor
    // copies or bookmarks opens in the language they're reading. replaceState,
    // not a router push: the page is already rendering in `l` from state, and
    // navigating would only refetch it.
    try {
      const url = new URL(window.location.href);
      url.searchParams.delete("lang");
      url.pathname = pathFor(stripLangPrefix(url.pathname), l);
      window.history.replaceState(null, "", url);
    } catch {
      /* history blocked — the language still applies, just not the URL */
    }
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
      if (vars)
        for (const [k, v] of Object.entries(vars))
          s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );

  const tCity = useCallback(
    (city: string) => CITY_KEYS[city]?.[lang] ?? city,
    [lang],
  );

  const tFeature = useCallback(
    (feature: string) =>
      FEATURE_KEYS[feature.trim().toLowerCase()]?.[lang] ?? feature,
    [lang],
  );

  return (
    <I18nContext.Provider
      value={{ lang, dir: LANGS[lang].dir, setLang, t, tCity, tFeature }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
